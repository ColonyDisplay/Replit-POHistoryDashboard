import { randomUUID } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const buildId = `${new Date().toISOString()}-${randomUUID()}`;
const generatedModule = resolve(projectRoot, "src/generated/uiBuildVersion.js");
const publicManifest = resolve(projectRoot, "public/ui-version.json");

await Promise.all([
  mkdir(dirname(generatedModule), { recursive: true }),
  mkdir(dirname(publicManifest), { recursive: true }),
]);

await Promise.all([
  writeFile(
    generatedModule,
    `// Generated by scripts/write-ui-version.mjs before each production build.\nexport const UI_BUILD_ID = ${JSON.stringify(buildId)};\n`,
    "utf8",
  ),
  writeFile(
    publicManifest,
    `${JSON.stringify({ buildId })}\n`,
    "utf8",
  ),
]);

console.log(`Generated UI build ${buildId}`);